import random


def gcd(a, b):
    """
    Вычисляет наибольший общий делитель (НОД) двух чисел a и b.
    """
    while b != 0:
        a, b = b, a % b
    return a


def lucas_primality_test(m, q_list, a_list, c=20):
    """
    Тест Люка на простоту (алгоритм 6.4)
    m: проверяемое число
    q_list: список простых делителей числа m-1
    a_list: список их показателей (для совместимости с формулой, не используется)
    c: количество итераций (по умолчанию 20)
    Возвращает: 'prime' (простое), 'composite' (составное) или 'inconclusive' (неоднозначно)
    """
    n = len(q_list)
    for attempt in range(c):
        k = 1
        # Шаг 2: выбрать случайное a
        a = random.randint(2, m - 2)
        if gcd(a, m) > 1:
            return 'составное'  # m и a не взаимно просты
        # Шаг 3: если попытки закончились
        # (в коде это контролируется внешним циклом)
        # Шаг 4: пока k <= n выполнять
        while k <= n:
            # 4.1: если a^(m-1) != 1 (mod m), то m составное
            if pow(a, m - 1, m) != 1:
                return 'составное'
            # 4.2: если a^((m-1)/q_k) == 1 (mod m), то вернуться к шагу 2
            if pow(a, (m - 1) // q_list[k - 1], m) == 1:
                break  # выйти из while, перейти к следующей попытке (новое a)
            # 4.3: иначе k = k + 1
            k += 1
        else:
            # Если цикл завершился без break, то m простое
            return 'простое'
    # Если ни одна попытка не дала однозначного ответа
    return 'неоднозначно'


def factorize(n):
    """
    Разлагает число n на простые множители.
    Возвращает два списка: q (простые множители) и a (их степени).
    """
    q = []  # Список для хранения простых множителей
    a = []  # Список для хранения соответствующих степеней
    d = 2   # Начинаем делить с самого маленького простого числа
    while d * d <= n:  # Проверяем делители до sqrt(n)
        count = 0  # Счётчик степени текущего делителя d
        while n % d == 0:  # Пока d делит n без остатка
            n //= d        # Делим n на d
            count += 1     # Увеличиваем степень для d
        if count > 0:      # Если d был делителем хотя бы один раз
            q.append(d)    # Добавляем d в список простых множителей
            a.append(count)  # Добавляем его степень
        d += 1  # Переходим к следующему потенциальному делителю
    if n > 1:  # Если после всех делений осталось число > 1, оно простое
        q.append(n)    # Добавляем его как простой множитель
        a.append(1)    # Его степень равна 1
    return q, a  # Возвращаем списки простых множителей и их степеней


